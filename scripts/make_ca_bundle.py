"""
Builds src/fw_ca_bundle.h: the root certificates the trickler trusts when it
downloads a firmware update from GitHub itself (Pico 2 W, display menu).
GitHub (raw.githubusercontent.com) uses certificates of one of these public
CAs; the list covers the CAs GitHub and its CDN have used and will likely use.

Usage

    python scripts/make_ca_bundle.py [--certs /etc/ssl/certs]
"""

import argparse
import os

ROOTS = [
    "USERTrust_RSA_Certification_Authority.pem",
    "USERTrust_ECC_Certification_Authority.pem",
    "Sectigo_Public_Server_Authentication_Root_R46.pem",
    "Sectigo_Public_Server_Authentication_Root_E46.pem",
    "DigiCert_Global_Root_G2.pem",
    "DigiCert_Global_Root_G3.pem",
    "GlobalSign_Root_CA_-_R3.pem",
    "GlobalSign_Root_CA_-_R6.pem",
    "GlobalSign_Root_R46.pem",
    "GlobalSign_Root_E46.pem",
    "ISRG_Root_X1.pem",
    "ISRG_Root_X2.pem",
]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--certs", default="/etc/ssl/certs")
    parser.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "fw_ca_bundle.h"))
    args = parser.parse_args()

    lines = []
    for name in ROOTS:
        with open(os.path.join(args.certs, name)) as fp:
            pem = fp.read().strip()
        lines.append(f"// {name[:-4].replace('_', ' ')}")
        lines.extend(f'"{line}\\n"' for line in pem.splitlines())

    with open(args.out, "w") as fp:
        fp.write("// Generated by scripts/make_ca_bundle.py, do not edit\n")
        fp.write("// Root certificates trusted for the firmware download from GitHub\n\n")
        fp.write("#ifndef FW_CA_BUNDLE_H_\n#define FW_CA_BUNDLE_H_\n\n")
        fp.write("static const char fw_ca_bundle[] =\n")
        fp.write("\n".join("    " + line for line in lines))
        fp.write(";\n\n#endif  // FW_CA_BUNDLE_H_\n")


if __name__ == "__main__":
    main()
